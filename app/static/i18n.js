let LANG = document.documentElement.lang === "az" ? "az" : "en";

function t(text, vars) {
  const out = (LANG === "az" && AZ[text]) || text;
  return vars ? out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : out;
}

// Messages sent from templates are stored in English; show them in the reader's language.
const MESSAGE_BODIES = [
  "Your vehicle {plate} needs to be moved. Please contact campus security.",
  "Your vehicle {plate} was involved in an incident on campus. Please contact campus security.",
  "The lights on your vehicle {plate} are on.",
];
function tMessage(body) {
  if (LANG !== "az") return body;
  const [first, ...rest] = String(body).split("\n\n");
  for (const tpl of MESSAGE_BODIES) {
    const re = new RegExp("^" + tpl.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace("\\{plate\\}", "(.+?)") + "$");
    const m = first.match(re);
    if (m) return [t(tpl, { plate: m[1] }), ...rest].join("\n\n");
  }
  return body;
}
